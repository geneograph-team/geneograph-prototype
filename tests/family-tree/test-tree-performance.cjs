'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
let clock = 100;
const context = vm.createContext({ performance: { now: () => clock } });
vm.runInContext(fs.readFileSync(path.join(__dirname, '../../src/core/application-performance.js'), 'utf8'), context);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../../src/modules/family-tree/tree-performance.js'), 'utf8'), context);
const perf = vm.runInContext('treePerf', context);
const recorder = vm.runInContext('appPerf', context);
const view = { orientation: 'horizontal', ancestorGenerations: 5, descendantGenerations: 3, showCousins: true };
assert.equal(perf.begin('private-project', 'focus', view), null);
assert.equal(perf.measure(null, 'people', () => 7), 7);
recorder.start();
const trace = perf.begin('private-project', 'focus', view);
assert.equal(perf.measure(trace, 'people', () => { clock += 12; return 8; }), 8);
perf.span(trace, 'people', 3);
perf.span(trace, 'secret-name', 100);
perf.count(trace, 'cards', 42);
perf.count(trace, 'private-person', 1);
perf.pass(trace, { startupMs: 5, solverMs: 20, privateName: 'secret-name', layout: {} });
perf.pass(trace, { solverMs: 30 });
perf.pass(trace, { solverMs: 40 });
perf.cache(trace, 'miss');
perf.mark(trace, 'pendingFeedback');
clock += 30;
perf.mark(trace, 'scenePublished');
perf.finish(trace, 'completed');
clock += 16;
perf.mark(trace, 'frameOpportunity');
const json = JSON.stringify(recorder.snapshot());
assert.ok(!json.includes('private-project') && !json.includes('secret-name') && !json.includes('private-person'));
let sample = JSON.parse(json).samples[0];
assert.equal(sample.stages.people.ms, 15);
assert.equal(sample.stages.people.calls, 2);
assert.equal(sample.counts.cards, 42);
assert.equal(sample.passTimings.length, 2);
assert.equal(sample.passTimings[0].solverMs, 20);
assert.equal(sample.cache, 'miss');
assert.equal(sample.totalMs, 42);
assert.equal(sample.milestones.frameOpportunity, 58);
const pending = perf.begin('private-project', 'focus', view);
recorder.stop();
assert.equal(recorder.snapshot().samples[1].status, 'stopped');
recorder.start();
perf.finish(pending, 'completed');
perf.span(pending, 'people', 999);
assert.equal(recorder.snapshot().samples[1].status, 'stopped');
assert.equal(recorder.snapshot().samples[1].stages.people, undefined);
for (let i = 0; i < 260; i++) perf.finish(perf.begin('private-project', 'zoom', view), 'completed');
assert.equal(recorder.snapshot().samples.length, 256);
assert.equal(recorder.snapshot().dropped, 6);
recorder.clear();
assert.equal(recorder.snapshot().samples.length, 0);
assert.equal(recorder.status().active, false);
recorder.start();
perf.finish(perf.begin('another-private-project', 'render', view), 'completed');
perf.finish(perf.begin('private-project', 'focus', view), 'completed');
assert.equal(recorder.status().active, true);
assert.equal(recorder.snapshot().samples.length, 2);
console.log('Tree performance trace timing, lifecycle, allowlist, and bounded retention passed.');

vm.runInContext(fs.readFileSync(path.join(__dirname, '../../src/modules/family-tree/tree-viewport.js'), 'utf8'), context);
context.treeProjectViewState = () => view;
context.assert = assert;
vm.runInContext(`
appPerf.clear();
appPerf.start();
const runtime = { projectId: 'private-project' };
const wheel = { type: 'wheel' }, lateWheel = { type: 'wheel' };
const press = { type: 'mousedown' }, release = { type: 'mouseup' };
startTreePerformanceGesture(runtime, wheel);
const first = runtime.performanceGesture.trace;
startTreePerformanceGesture(runtime, press);
const drag = runtime.performanceGesture.trace;
finishTreePerformanceGesture(runtime, wheel);
finishTreePerformanceGesture(runtime, null);
assert.equal(first.status, 'canceled');
assert.equal(drag.status, 'pending');
rememberTreePerformanceGestureEnd(runtime, release);
finishTreePerformanceGesture(runtime, release);
assert.equal(drag.status, 'completed');
assert.equal(runtime.performanceGesture, null);

startTreePerformanceGesture(runtime, lateWheel);
finishTreePerformanceGesture(runtime, wheel);
assert.equal(runtime.performanceGesture.trace.status, 'pending');
finishTreePerformanceGesture(runtime, lateWheel);
assert.equal(appPerf.snapshot().samples.at(-1).status, 'completed');

startTreePerformanceGesture(runtime, { type: 'touchstart' });
const touchCancel = { type: 'touchcancel' };
rememberTreePerformanceGestureEnd(runtime, touchCancel);
finishTreePerformanceGesture(runtime, touchCancel);
assert.equal(appPerf.snapshot().samples.at(-1).status, 'canceled');

startTreePerformanceGesture(runtime, wheel);
appPerf.stop();
const stopped = runtime.performanceGesture.trace;
appPerf.start();
startTreePerformanceGesture(runtime, lateWheel);
finishTreePerformanceGesture(runtime, wheel);
assert.equal(stopped.status, 'stopped');
assert.equal(runtime.performanceGesture.trace.status, 'pending');
cancelTreePerformanceGesture(runtime);
assert.equal(appPerf.snapshot().samples.at(-1).status, 'canceled');

startTreePerformanceGesture(runtime, wheel);
const discarded = runtime.performanceGesture.trace;
appPerf.clear();
appPerf.start();
startTreePerformanceGesture(runtime, lateWheel);
finishTreePerformanceGesture(runtime, wheel);
assert.equal(discarded.status, 'stopped');
assert.equal(appPerf.snapshot().samples.length, 1);
assert.equal(appPerf.snapshot().samples[0].status, 'pending');
for (let index = 0; index < 256; index++) appPerf.run('People', 'render', () => null);
finishTreePerformanceGesture(runtime, lateWheel);
assert.equal(appPerf.snapshot().dropped, 1);
assert.equal(runtime.performanceGesture, null);
assert.ok(appPerf.snapshot().samples.every(sample => sample.status === 'completed'));
appPerf.stop();
`, context);
console.log('Tree gesture ownership: supersession, stale ends, native cancel, eviction, Stop and restart passed.');

